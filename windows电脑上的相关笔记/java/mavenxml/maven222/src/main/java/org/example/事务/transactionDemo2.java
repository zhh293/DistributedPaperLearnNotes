/*三、事务的传播行为 —— 方法调用时的 “事务规则”
场景：
在代码中，一个带事务的方法 A 调用另一个方法 B，这时候 B 的事务该怎么处理？
比如：

java
@Transactional // 方法A有事务（传播行为默认是REQUIRED）
public void methodA() {
    // 操作1（数据库A）
    methodB(); // 调用方法B
    // 操作2（数据库A）
}

@Transactional // 方法B的事务传播行为是什么？
public void methodB() {
    // 操作3（数据库A或其他库）
}

传播行为就是定义方法 B 的事务如何与方法 A 的事务互动。
常见的传播行为（以 Spring 框架为例）：

传播行为	含义（通俗解释）
REQUIRED	默认值：如果方法 A 有事务，方法 B 加入 A 的事务；如果 A 没有，B 自己开启新事务。
REQUIRES_NEW	方法 B新建一个事务，独立于方法 A 的事务。如果 A 出错回滚，不影响 B 已提交的结果。
NESTED	方法 B 是 A 的嵌套事务，像 “子任务”。如果 A 回滚，B 也回滚；但 B 单独回滚，A 可能不受影响。
SUPPORTS	方法 B “支持” 事务：如果 A 有事务，B 加入；如果 A 没有，B 就以非事务方式执行。
NOT_SUPPORTED	方法 B不使用事务：即使 A 有事务，B 也会挂起 A 的事务，单独以非事务方式执行。
NEVER	方法 B禁止事务：如果 A 有事务，直接报错；只有 A 无事务时，B 才执行。
MANDATORY	方法 B必须在事务中执行：如果 A 没有事务，直接报错；如果 A 有，B 加入。*/

















