package org.example;

public class 乐观锁 {
   public static void main(String[] args) {
       //针对秒杀场景，我们可以使用乐观锁，来保证库存的并发安全

     /* 场景：两人同时抢购同一商品（库存扣减）
      假设数据库中商品库存初始值：

      id	stock
      1   	10
      不加版本号的流程（无锁保护）：
      用户 A 和用户 B 同时查询库存
      两人都读到 stock=10，并各自在本地计算新库存 stock=9（准备扣减 1 件）。
      用户 A 先提交更新
      SQL：UPDATE product SET stock = 9 WHERE id = 1
      执行成功，库存变为 9。
      用户 B 随后提交更新
      SQL：UPDATE product SET stock = 9 WHERE id = 1
      此时数据库中 stock 已经是 9，但用户 B 的更新条件是 id=1（没有版本号校验），因此会覆盖用户 A 的结果，库存仍为 9。

      问题：
      两人各扣减 1 件，但库存只减少了 1 件（预期减少 2 件），更新丢失。
      原因：用户 B 的更新没有感知到用户 A 已经修改过数据，直接覆盖了结果。*/




   /*   乐观锁概念：相信世界充满爱，但也有准备
      想象一下，你和朋友一起编辑一份共享文档（比如 Google Docs）。你正在修改一个段落时，乐观锁的逻辑是这样的：

      乐观假设："我相信朋友不会同时修改同一段内容，即使他改了，系统也能提醒我"
      版本控制：每次编辑时，系统会给文档一个 "版本号"（比如 v1, v2, v3...）
      提交检查：当你保存时，系统会检查："现在的版本号是不是我编辑前看到的那个？"
      如果是（没人修改过），顺利保存，版本号 +1
      如果不是（有人抢先修改了），系统会说："嘿，文档已经被更新了，你需要先合并最新内容再保存！"

      这就是乐观锁的核心：假设并发冲突很少发生，但通过版本号机制检测冲突，确保数据一致性。*/
      /*乐观锁的实际用处：
      数据库并发更新
      场景：多个用户同时修改同一条订单数据
      实现：数据库表中添加 version 字段
      流程：
      sql
              -- 查询数据时获取当前版本
      SELECT amount, version FROM orders WHERE id=123;
      -- 假设 version=1，用户修改金额后提交
      UPDATE orders
      SET amount=100, version=version+1  -- 版本号+1
      WHERE id=123 AND version=1;  -- 关键：只在版本号匹配时更新
              -- 如果更新成功（影响行数=1），说明没有并发冲突
              -- 如果更新失败（影响行数=0），说明数据已被其他事务修改，需要重试*/





   }
}
