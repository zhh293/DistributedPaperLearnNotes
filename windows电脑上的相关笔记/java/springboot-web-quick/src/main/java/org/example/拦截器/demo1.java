package org.example.拦截器;

public class demo1 {
    /*过滤器（Filter）
    过滤器是一种更底层的组件，通常在请求到达目标资源之前进行预处理，或者在响应返回客户端之前进行后处理。过滤器主要用于：

    请求 / 响应内容的转换（如编码转换）
    安全验证（如 URL 级别的权限控制）
    日志记录
            性能监控
    请求过滤（如阻止特定 IP 访问）

    过滤器的工作原理类似于 "管道 - 过滤器" 模式，请求在到达目标资源前会通过一系列过滤器，每个过滤器执行特定的任务后将请求传递给下一个过滤器或目标资源。
    拦截器（Interceptor）
    拦截器是一种更高级的组件，通常在应用程序的业务逻辑层和表示层之间工作。拦截器主要用于：

    事务管理
            日志记录
    权限验证
            性能监控
    缓存管理

    拦截器的工作原理类似于 AOP（面向切面编程），它可以在方法执行前后、异常抛出时等特定点插入自定义逻辑。*/
}
/*
特性  	过滤器 (Filter)	   拦截器 (Interceptor)
应用范围	Servlet 容器级别	   应用程序级别
实现方式	基于 Servlet API 	  基于 Java 反射或动态代理
执行顺序	在 Servlet 之前执行	   在 Servlet 之后，Controller 之前执行
访问对象	只能访问 request 和 response	  可以访问 action 上下文、值栈里的对象
生命周期	随 Servlet 容器启动而启动	   随应用程序启动而启动
性能开销	   较低	               较高（涉及反射）*/
/*
使用过滤器处理低级任务：如字符编码转换、静态资源缓存控制等。
使用拦截器处理高级任务：如权限验证、事务管理等。
避免在过滤器中处理业务逻辑：过滤器应保持简单，专注于请求 / 响应的预处理和后处理。
合理配置执行顺序：多个过滤器和拦截器的执行顺序会影响最终结果，应合理规划。*/
//是的，在 Web 请求处理流程 中，过滤器（Filter）的执行顺序确实先于拦截器（Interceptor）。