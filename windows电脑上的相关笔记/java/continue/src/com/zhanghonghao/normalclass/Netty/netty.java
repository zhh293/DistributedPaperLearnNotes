/*BIO（同步阻塞 IO）：
比喻：
你去银行办业务，只能在一个窗口排队。窗口柜员一次只能接待一个客户，在他处理你的业务时（比如存钱、转账），你必须一直等着，不能做别的事。直到柜员处理完，你才能离开，下一个客户才能继续办理。

关键点：

同步：你必须 “等待业务处理完成” 才能继续下一步。
阻塞：在等待过程中，你什么都不能干，只能干等。

应用场景：

客户端连接少且固定的场景（如传统的数据库连接）。
优点：代码简单，容易理解和实现。
缺点：效率低。如果有大量客户端同时连接，服务器需要为每个客户端创建一个线程，会消耗大量资源（比如 1000 个客户端就需要 1000 个线程），容易导致服务器崩溃。
NIO（同步非阻塞 IO）：
比喻：
你去银行办业务，现在有一个 “取号机” 和一个 “大堂经理”。你取号后，可以坐在休息区玩手机、看报纸（做其他事）。大堂经理会在轮到你时叫号（通知你），这时你再去窗口办理业务。

关键点：

同步：你仍需主动去窗口办理业务（不能由别人代劳）。
非阻塞：在等待叫号的过程中，你可以自由做其他事，不用一直盯着窗口。

核心组件：

Channel（通道）：类似 “数据传输的管道”，可以同时进行读写（比如网络连接、文件操作）。
Buffer（缓冲区）：数据存储的容器，读写数据都通过它（类似 “水桶”）。
Selector（选择器）：核心！一个线程可以管理多个 Channel，监控它们的状态（如 “数据可读”“数据可写”），当某个 Channel 有事件发生时才去处理。*/
