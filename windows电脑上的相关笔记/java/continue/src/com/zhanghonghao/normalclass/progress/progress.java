        /*并发与并行
        * 并发，在同一时刻，有多个指令在单个CPU上交替执行
        * 并行，在同一时刻，有多个指令在多个CPU上同时执行
        * CPU分为几核几线程
        * 核心（Core）
含义：CPU 核心是 CPU 中独立的处理单元，也被称为内核。每个核心都可以独立执行指令和处理数据，就像是一个独立的小型计算机。
作用：核心数量越多，CPU 能够同时处理的任务就越多，并行处理能力就越强。例如，在多任务处理时，每个核心可以分别处理不同的任务，如一个核心用于运行文字处理软件，另一个核心用于同时下载文件，这样可以提高整体的工作效率。在进行复杂的计算任务，如视频渲染、3D 建模时，多个核心可以协同工作，将任务分解并同时处理，大大缩短处理时间。
线程（Thread）
含义：线程是 CPU 核心在执行任务时的一条执行路径。可以把线程理解为核心中的一个 “虚拟处理器”，它能够在一个核心上实现多个任务的并发执行。
作用：通过多线程技术，CPU 可以在一个核心上交替执行多个线程的任务，从而提高核心的利用率。比如，当一个线程在等待数据从内存中传输时，CPU 可以切换到另一个线程继续执行，而不是让核心处于空闲状态。这在处理大量轻量级任务时非常有效，能够提高系统的响应速度和整体性能。*/
        /*一个物理核心能否同时执行多个线程，取决于 CPU 是否支持超线程技术（Hyper-Threading）或同步多线程（SMT）。以下是详细解释：
        1. 不支持超线程的核心（单核单线程）
        原理：
        单个物理核心同一时间只能执行1 个线程，通过时间片轮转（CPU 快速切换任务）模拟多线程并发。
        表现：
        任务看似 “同时运行”，但实际是交替执行，存在微小延迟。例如：
        边打字边听音乐时，CPU 会在两个任务间快速切换，用户感知不到延迟。
        但在高负载下（如同时渲染视频 + 压缩文件），性能会明显下降。
        2. 支持超线程的核心（单核多线程）
        原理：
        通过硬件优化（如增加寄存器、指令队列等），每个物理核心可同时处理2 个线程（例如 Intel 的超线程技术）。
        表现：
        硬件层面：两个线程的指令可以并行执行（如一个线程等待内存时，另一个线程继续运算）。
        性能提升：多线程任务中，效率比单核单线程提升约30%-50%，但无法达到两个物理核心的性能。
        目前提到的多核多线程中的线程，绝大多数情况下是指通过 ** 超线程技术（Hyper-Threading）或同步多线程（SMT）** 实现的虚拟线程。
        */
