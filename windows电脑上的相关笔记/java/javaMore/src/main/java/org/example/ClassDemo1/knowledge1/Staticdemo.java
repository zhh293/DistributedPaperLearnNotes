/*
方法区 vs 堆
方法区存储类的元数据（如静态变量、常量、方法字节码），堆存储对象实例。
Java 8 后，方法区（元空间）使用本地内存，而堆仍使用 JVM 管理的内存，两者相互独立。
静态变量的线程安全
静态变量被所有线程共享，若涉及多线程修改，需通过同步机制（如synchronized、Lock）保证线程安全。
为什么静态方法不能访问非静态成员？
非静态成员属于对象实例（在堆中），而静态方法属于类（在方法区），类加载时可能还未创建对象，因此无法直接访问。
总结
JVM 内存核心区域：方法区（元空间）、堆、虚拟机栈、本地方法栈、程序计数器。
static 成员位置：均位于方法区（元空间），与类的元数据一同存储，不依赖对象实例。
关键区别：静态成员属于类级别，生命周期与类加载 / 卸载绑定；实例成员属于对象级别，生命周期与对象创建 / 销毁绑定。


一、语法糖：对象访问静态数据的本质
Java 允许通过对象引用访问静态成员（如obj.staticField），但这只是一种语法糖。
JVM 在编译和运行时会直接忽略对象引用，而是通过类名来定位静态成员。
*/

