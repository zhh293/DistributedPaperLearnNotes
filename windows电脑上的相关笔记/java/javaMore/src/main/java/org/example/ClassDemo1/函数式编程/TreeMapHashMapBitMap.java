    /*HashMap、TreeMap、BitMap 是三种完全不同的数据结构，核心区别体现在存储方式、功能定位、适用场景上。以下用 “生活场景” 类比讲解：
    一、HashMap：「快递驿站」式存储
    核心特点：

    数据结构：数组 + 链表 / 红黑树（JDK8+），通过哈希值定位元素。
    功能：以 “键值对（Key-Value）” 形式存储任意对象，支持快速增删查。
    效率：插入、删除、查询均为 O(1)（哈希无冲突时）。
    顺序：无序（键的顺序由哈希决定，与插入 / 大小无关）。
    适用场景：大多数 “键值对” 场景（如缓存、配置映射）。

    生活类比：
    把快递驿站的货架想象成 HashMap：

    每个快递的 “取件码” 是 Key（需唯一），快递本身是 Value。
    驿站通过取件码的哈希（如取件码后三位）快速定位货架位置，无需按顺序排列。
    优点：找快递快（O (1)）；缺点：快递摆放无序，无法直接 “按取件码排序” 找。
    二、TreeMap：「图书馆书架」式存储
    核心特点：

    数据结构：红黑树（一种自平衡二叉树）。
    功能：以 “键值对” 存储，但自动按 Key 排序（自然顺序或自定义 Comparator）。
    效率：插入、删除、查询均为 O(log n)（树结构的平衡操作）。
    顺序：有序（遍历时键自动升序 / 降序）。
    适用场景：需要 “按键排序” 的场景（如排行榜、时间线聚合）。

    生活类比：
    把图书馆的书架想象成 TreeMap：

    每本书的 “ISBN 号” 是 Key（需唯一），书的内容是 Value。
    书架按 ISBN 号从小到大排列，找书时需按顺序遍历或二分查找。
    优点：书有序摆放，能快速找到 “某范围的书”（如 ISBN 以 978 开头的）；缺点：插入新书时需调整书架顺序，耗时比快递驿站略久。
    三、BitMap：「灯控开关」式存储
    核心特点：

    数据结构：二进制位（bit）数组，每个位仅存 0/1。
    功能：仅记录 “整数是否存在”（无法存 Value），空间极致压缩。
    效率：插入、查询均为 O(1)（位运算）。
    顺序：无（仅记录存在性，不关心顺序）。
    适用场景：大规模整数去重、二值统计（如签到、在线状态）。

    生活类比：
    把整栋楼的 “灯控开关” 想象成 BitMap：

    每个房间的灯对应一个 “位”（0 = 关，1 = 开），房间号是整数（如 101、202）。
    只需 1 位就能表示 “某房间灯是否开”，1000 个房间仅需 1000/8 = 125 字节。
    优点：极省空间，查 “某房间灯是否开” 只需瞬间；缺点：只能存 “是否存在”，无法存 “灯的亮度、颜色” 等额外信息。
    四、三者核心差异总结
    维度	HashMap	TreeMap	BitMap
    存储内容	键值对（Key-Value）	键值对（Key-Value）	仅整数的 “存在性”（无 Value）
    数据结构	数组 + 链表 / 红黑树	红黑树	二进制位数组
    顺序性	无序	按键有序（升序 / 降序）	无顺序
    效率	增删查 O (1)	增删查 O (log n)	增删查 O (1)
    空间占用	较高（存对象 overhead）	较高（树结构 + 对象 overhead）	极低（按位存储）
    典型场景	缓存、业务对象映射	排行榜、有序字典	签到统计、用户在线状态、去重
    五、一句话记忆
    HashMap：要 “快” 不要 “顺序”，选我！
    TreeMap：要 “顺序” 能接受 “稍慢”，选我！
    BitMap：要 “极致省空间” 且只存 “整数是否存在”，选我！

            （比如：统计 1000 万用户是否签到 → BitMap；存储用户 ID 到信息的映射 → HashMap；按用户积分排序 → TreeMap）*/


