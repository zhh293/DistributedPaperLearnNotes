/*
多态的形式
1. 父类引用指向子类对象
2. 父类引用调用子类特有方法
3. 父类引用调用父类方法
格式
        父类引用 = new 子类对象();
        同一个类型的对象，执行同一个行为，在不同状态下会表现出不同的行为特征
        对于方法的调用，编译看左边，运行看右边
        对于变量的调用，编译看左边，运行也看左边




        多态使用前提
        必须存在父类类型的变量引用子类类型的对象
        必须存在继承和实现关系
        需要存在方法的重写*/
