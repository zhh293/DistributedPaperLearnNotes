package Netty;

public class RPC框架介绍 {
    /*通俗易懂清晰的讲解一下RPC是什么
    要理解 RPC，我们可以从生活中的一个场景说起：

    假设你在公司（客户端），想知道家里冰箱里还有多少瓶可乐（服务器上的数据）。
    你不需要亲自跑回家打开冰箱看 —— 你可以给家里的家人打个电话（这就是 “远程调用” 的过程），说 “帮我看看冰箱里有几瓶可乐”（调用 “查可乐” 这个 “功能 / 函数”），家人看完告诉你结果（返回数据）。

    这里的核心逻辑就是：你（客户端）想使用一个 “功能”，但这个功能不在你身边（在远程服务器上），于是你通过某种方式（比如网络）“调用” 了这个远程功能，最后拿到了结果。

    在计算机里，这个逻辑就叫 RPC（Remote Procedure Call，远程过程调用）：

            “Procedure（过程）” 可以理解为 “函数 / 方法”（比如 “查可乐数量” 的功能）；
            “Remote（远程）” 指这个函数不在本地电脑，而在另一台服务器上；
            “Call（调用）” 就是你通过代码触发这个远程函数的过程。

    RPC 的关键作用是：** 让开发者调用远程函数时，感觉和调用本地函数一样简单 **。
    比如，本地调用可能是 getCokeCount()，用了 RPC 后，远程调用还是写 getCokeCount()，不需要自己处理 “怎么连服务器、怎么发请求、怎么解析返回数据”
    这些网络细节 ——RPC 框架会帮你自动搞定这些（就像你打电话时，不用关心信号怎么传输，只需要说话和听就行）。

    总结一下：
    RPC 就是一种 “让你像调用本地函数一样，调用远程服务器上的函数” 的技术，它帮你屏蔽了复杂的网络通信细节，让跨服务器的功能调用变得简单。

            （比如你用手机 App 刷短视频，App（客户端）需要获取 “推荐的视频列表”，这个功能可能在远方的服务器上，App 就是通过 RPC 调用了服务器上的 “获取推荐视频” 函数，才拿到你看到的内容。）
    也就说如果没有RPC协议，调用远程服务器的方法需要先连接上服务器，然后想办法发送相应的请求来调用想要的方法（可能是http协议来访问特定的接口）获取到数据后再想办法送回来？？？
    你的理解非常准确！

    如果没有 RPC，远程调用确实需要开发者手动处理几乎所有网络通信细节，步骤会很繁琐，大致流程是这样的：

    建立连接：手动创建网络连接（比如用 TCP 协议三次握手建立连接，或者通过 HTTP 协议基于 TCP 做封装）。
    定义请求格式：自己约定 “怎么告诉服务器要调用哪个方法、传什么参数”—— 比如用 JSON 格式写一个字符串：{"method":"getCokeCount","params":[]}。
    发送请求：通过建立好的连接（比如 HTTP 的 POST 请求，或者直接用 TCP 发送字节流），把上面的请求数据传给服务器。
    服务器处理：服务器端需要手动写代码解析收到的数据（比如解析 JSON，找到要调用的方法名和参数），然后执行对应的方法。
    返回结果：服务器执行完后，再把结果（比如{"result":3}）按照约定的格式打包，通过连接发回给客户端。
    客户端解析：客户端收到数据后，手动解析结果（比如解析 JSON 拿到 3），还要处理各种异常（比如连接超时、数据格式错误、服务器崩溃等）。

    简单说，没有 RPC 的话，远程调用就像 “裸写网络通信”：你得自己搭桥（建立连接）、自己写 “密码本”（数据格式）、自己跑过去送信（发送请求）、自己等回信（处理响应）、自己翻译回信（解析结果），
    中间任何一步出问题（比如桥断了、密码本看错了）都得自己搞定。


    而 RPC 的作用，就是把这些 “搭桥、写密码本、送信、翻译” 的工作全部自动化，你只需要像调用本地方法一样写一行代码（比如getCokeCount()），剩下的交给 RPC 框架就行。


            （补充个小细节：HTTP 其实可以作为 RPC 的 “传输工具” 之一 —— 有些 RPC 框架底层用 HTTP 传数据，但 RPC 不止于此，还会封装方法映射、序列化（把参数转成字节流）、反序列化（把字节流转回参数）等逻辑，比单纯的 HTTP 接口调用更 “傻瓜化”。）*/
}
