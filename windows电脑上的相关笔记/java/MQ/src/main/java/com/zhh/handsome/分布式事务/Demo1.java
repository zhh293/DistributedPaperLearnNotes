/*要理解分布式事务，咱们先从 “你熟悉的场景” 切入，再拆概念、讲方案 —— 全程不用复杂术语，就像聊日常事儿一样。
一、先搞懂：为什么会有 “分布式事务”？
咱们先想个简单的 “本地事务” 例子：
你在超市买东西，结账时收银员要做两件事：① 扣你银行卡里的钱（支付系统）；② 记超市的销售账（财务系统）。如果这两件事都在同一个数据库里操作（比如超市的内部系统），那很简单：要么两件事都成，要么都不成（比如钱扣了但账没记，系统会自动把钱退回去）—— 这就是 “本地事务”，核心是 “要么全成，要么全败”（ACID 特性）。

但现在系统都是 “分布式” 的 —— 比如你在电商 APP 下单：

下单要改「订单库」（订单服务负责，数据库 A）；
扣库存要改「库存库」（库存服务负责，数据库 B）；
减积分要改「用户库」（用户服务负责，数据库 C）。

这时候问题来了：如果「订单建好了」，但「库存没扣成」（比如库存服务宕机了），会怎么样？—— 订单显示 “已下单”，但库存还是满的，可能导致 “超卖”（别人还能买这个商品）；反过来，如果「库存扣了」但「订单没建好」，又会导致 “库存少了但没订单”，数据乱了。

所以，分布式事务的核心需求就是：
跨多个服务、多个数据库的操作，必须满足 “要么全成，要么全败”—— 哪怕服务 / 数据库之间网络断了、机器坏了，最终数据也得是对的。
二、分布式事务的核心矛盾：强一致性很难！
你可能会问：“直接让这些服务同步执行，等所有操作都成了再结束不行吗？”
不行！因为分布式系统里有「不可靠因素」：

网络可能断（订单服务发消息给库存服务，消息丢了）；
服务可能宕机（库存服务刚扣完库存，还没告诉订单服务就挂了）；
数据库可能卡壳（用户库半天没响应）。

如果硬要 “等所有操作都确认成功”，会导致系统 “卡住”（比如订单服务一直等库存服务的回复，其他订单也处理不了）—— 这就是 “强一致性” 的代价。

所以实际场景中，大部分分布式事务追求的是「最终一致性」：不是 “瞬间全对”，而是 “过一会儿（比如几秒、几分钟）所有数据都会对”，用户能接受这个延迟。




方案 1：2PC（两阶段提交）—— 传统 “强一致性” 方案
可以理解为 “公司开会投票”：找一个 “协调者”（比如专门的事务协调服务），再找两个 “参与者”（订单服务、库存服务），分两步走：
第一步：准备阶段（投票）
协调者对订单服务说：“你先试试建订单，别真提交，告诉我能不能成？”
订单服务操作数据库 A 建订单（但不提交事务），如果没问题，回复 “可以”；如果失败（比如没权限），回复 “不行”。
协调者再对库存服务做同样的事：“你试试扣库存，别提交，告诉我能不能成？”
库存服务操作数据库 B 扣库存（不提交），回复 “可以” 或 “不行”。
第二步：提交 / 回滚阶段（执行投票结果）
如果两个参与者都回复 “可以”：协调者发指令 “所有人提交！”，订单服务提交事务（订单生效），库存服务提交事务（库存扣减）—— 事务成功。
如果有一个参与者回复 “不行”（比如库存不够）：协调者发指令 “所有人回滚！”，订单服务删掉刚建的订单，库存服务恢复库存 —— 事务失败。

例子：你在 APP 下单，系统先 “试探” 建订单、扣库存，都没问题再确认，有问题就全撤。
优点：实现简单，能保证强一致性（要么全成，要么全败）。
缺点：

阻塞！准备阶段如果某个参与者卡壳（比如库存服务没回复），所有服务都得等着，没法处理其他请求；
协调者是 “单点风险”：如果协调者宕机，参与者永远不知道该提交还是回滚，只能卡住。

现在很少用纯 2PC 了（比如 MySQL 的 XA 事务就是 2PC，但性能差），只在对一致性要求极高、并发低的场景用（比如银行转账）。



方案 4：本地消息表 —— 最简单的 “最终一致性” 方案
这个方案的核心是 “把消息存在本地数据库，靠定时任务慢慢同步”，完全不依赖复杂的中间件，适合中小团队。

还是 “下单 + 扣库存” 场景，步骤如下：
        1. 订单服务：本地事务（建订单 + 写消息表）
订单服务的数据库里，除了 “订单表”，再建一个 “本地消息表”（记录要发给库存服务的消息）。
执行一个本地事务：

操作 1：往 “订单表” 插一条订单记录；
操作 2：往 “本地消息表” 插一条消息（内容：“订单 ID=123，需要扣 2 个库存”，状态 =“待发送”）。

关键：这两个操作在同一个本地事务里 —— 要么都成，要么都败（比如订单没建好，消息也不会存），避免 “有订单没消息” 的情况。
        2. 定时任务：发消息到 MQ
订单服务起一个定时任务（比如每 10 秒跑一次），扫描 “本地消息表” 里 “待发送” 的消息，把消息发给 RabbitMQ（库存服务监听的队列）。

如果发成功了：把消息状态改成 “已发送”；
如果发失败了（比如 MQ 宕机）：下次定时任务再重试（直到发成功）。
        3. 库存服务：消费消息 + 发确认
库存服务监听 MQ，收到消息后：

执行 “扣库存” 操作；
扣成功后，发一条 “确认消息” 到 MQ（订单服务监听的队列）。
        4. 订单服务：确认消息，更新状态
订单服务收到 “确认消息” 后，把 “本地消息表” 里对应消息的状态改成 “已完成”—— 整个事务结束。
如果一直没收到确认（比如库存服务失败）：定时任务会重复发消息，库存服务重试扣库存（直到成功）。

优点：超级简单！不用学复杂框架，靠本地数据库和定时任务就能实现，中小团队能快速落地。
缺点：要手动建 “本地消息表”，定时任务会有延迟（比如 10 秒重试一次，库存可能 10 秒后才扣），适合对延迟不敏感的场景。
常用场景：非核心业务（比如下单后发通知、日志同步），或中小团队的核心业务。
方案 5：事务消息（MQ 帮你做消息表）
这个方案是 “本地消息表” 的升级版 —— 把 “本地消息表” 的工作交给 MQ 来做（比如 RocketMQ 支持事务消息，RabbitMQ 需要自己实现类似逻辑），不用自己建表和写定时任务。

还是 “下单 + 扣库存”，以 RocketMQ 为例：
        1. 订单服务：发 “半消息”
订单服务先给 RocketMQ 发一条 “半消息”（Half Message）—— 这种消息在 MQ 里是 “不可见” 的（库存服务看不到）。
MQ 收到半消息后，回复 “收到了”。
        2. 订单服务：执行本地事务
订单服务执行 “建订单” 的本地事务：

如果建订单成功：给 MQ 发 “确认消息”，MQ 把 “半消息” 改成 “可见”（库存服务能看到）；
如果建订单失败：给 MQ 发 “回滚消息”，MQ 删掉 “半消息”。
        3. 库存服务：消费消息 + 处理
库存服务看到 MQ 里 “可见” 的消息，执行 “扣库存” 操作，处理完就结束。
        4. 异常重试：MQ 的 “回查机制”
如果订单服务发完半消息后，突然宕机了（没发确认 / 回滚），MQ 会定时 “回查” 订单服务：“你之前发的半消息，本地事务成功了吗？”
订单服务查自己的订单表：

如果订单存在（成功）：发确认消息；
如果订单不存在（失败）：发回滚消息。

优点：比本地消息表简单（不用自己建表、写定时任务），MQ 帮你搞定一致性，延迟低。
缺点：依赖特定 MQ（比如 RocketMQ 原生支持，RabbitMQ 要自己适配），有学习成本。
常用场景：中大型团队，核心业务（下单、支付），对延迟和简洁性有要求。*/



